// Inputs: the inputs manifest (existing documents, notes and schema files, listed by path or URL with a checksum)
// and the freshness check that decides whether the source needs a new scan. Content is never copied into prompts:
// agents get paths and links, as with all evidence in this toolkit.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative, resolve, sep } from 'node:path';

const SKIP_DIRS = new Set(['.git', 'node_modules', 'target', 'build', 'dist', '.idea', '.vscode', '__pycache__', '.venv']);
const KINDS = {
  '.md': 'markdown', '.txt': 'text', '.pdf': 'pdf', '.docx': 'word', '.doc': 'word', '.xlsx': 'spreadsheet', '.csv': 'csv',
  '.pptx': 'slides', '.html': 'html', '.json': 'json', '.yaml': 'yaml', '.yml': 'yaml', '.xml': 'xml',
  '.ddl': 'ddl', '.sql': 'sql', '.dcl': 'dclgen', '.png': 'image', '.jpg': 'image', '.svg': 'image',
};

const isUrl = (s) => /^https?:\/\//i.test(s);
const posix = (p) => p.split(sep).join('/');

function* walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') && e.name !== '.') continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) yield* walk(p); } else if (e.isFile()) yield p;
  }
}

/** Expand config entries (files, folders, URLs) into manifest rows. Missing paths are reported, not fatal. */
export function collect(entries, role, root) {
  const rows = [];
  for (const entry of entries) {
    if (isUrl(entry)) { rows.push({ role, ref: entry, kind: 'link' }); continue; }
    const abs = resolve(root, entry);
    if (!existsSync(abs)) { rows.push({ role, ref: entry, kind: 'missing' }); continue; }
    const files = statSync(abs).isDirectory() ? [...walk(abs)] : [abs];
    for (const f of files.sort()) {
      const data = readFileSync(f);
      rows.push({
        role, ref: posix(relative(root, f)), kind: KINDS[extname(f).toLowerCase()] || 'file',
        bytes: data.length, sha256: createHash('sha256').update(data).digest('hex').slice(0, 12),
      });
    }
  }
  return rows;
}

/** Write <analysisDir>/inputs.md and return { path, rows }. */
export function writeManifest(cfg, root) {
  const rows = [...collect(cfg.docs, 'document', root), ...collect(cfg.schema, 'schema', root)];
  const dir = resolve(root, cfg.analysisDir);
  mkdirSync(dir, { recursive: true });
  const link = (r) => (r.kind === 'link' ? `<${r.ref}>` : r.kind === 'missing' ? `${r.ref} (not found)` : `[${r.ref}](${posix(relative(dir, resolve(root, r.ref)))})`);
  const md = [
    '# Inputs', '',
    'Generated by `l2m`. Documents, notes and schema files given as inputs, by path or link with a short sha256, so a document',
    'can say exactly which version of an input it was written from. Read them from here; cite them as links; never paste their content.', '',
    '| Role | Input | Kind | Size | sha256 |', '|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.role} | ${link(r)} | ${r.kind} | ${r.bytes ?? '—'} | ${r.sha256 ?? '—'} |`),
  ];
  if (!rows.length) md.push('| — | none | — | — | — |');
  const path = join(dir, 'inputs.md');
  writeFileSync(path, `${md.join('\n')}\n`);
  return { path, rows };
}

/** True when inventory.json is missing or older than the newest file in the source tree. */
export function needsScan(srcDir, inventoryPath) {
  if (!existsSync(inventoryPath)) return true;
  const scanned = statSync(inventoryPath).mtimeMs;
  for (const f of walk(srcDir)) if (statSync(f).mtimeMs > scanned) return true;
  return false;
}
